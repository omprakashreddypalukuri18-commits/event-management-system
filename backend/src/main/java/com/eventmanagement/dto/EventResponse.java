package com.eventmanagement.dto;

import com.eventmanagement.model.EventStatus;

import java.time.LocalDate;
import java.time.LocalTime;

/**
 * What the frontend actually receives for an event: plain fields only
 * (no JPA entity / lazy proxies), plus computed registeredCount & availableSeats.
 */
public class EventResponse {

    private Long id;
    private String name;
    private String description;
    private LocalDate eventDate;
    private LocalTime eventTime;
    private String venue;
    private String category;
    private Integer maxParticipants;
    private Double ticketPrice;
    private EventStatus registrationStatus;
    private Long organizerId;
    private String organizerName;
    private long registeredCount;
    private long availableSeats;

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDate getEventDate() {
        return eventDate;
    }

    public void setEventDate(LocalDate eventDate) {
        this.eventDate = eventDate;
    }

    public LocalTime getEventTime() {
        return eventTime;
    }

    public void setEventTime(LocalTime eventTime) {
        this.eventTime = eventTime;
    }

    public String getVenue() {
        return venue;
    }

    public void setVenue(String venue) {
        this.venue = venue;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public Integer getMaxParticipants() {
        return maxParticipants;
    }

    public void setMaxParticipants(Integer maxParticipants) {
        this.maxParticipants = maxParticipants;
    }

    public Double getTicketPrice() {
        return ticketPrice;
    }

    public void setTicketPrice(Double ticketPrice) {
        this.ticketPrice = ticketPrice;
    }

    public EventStatus getRegistrationStatus() {
        return registrationStatus;
    }

    public void setRegistrationStatus(EventStatus registrationStatus) {
        this.registrationStatus = registrationStatus;
    }

    public Long getOrganizerId() {
        return organizerId;
    }

    public void setOrganizerId(Long organizerId) {
        this.organizerId = organizerId;
    }

    public String getOrganizerName() {
        return organizerName;
    }

    public void setOrganizerName(String organizerName) {
        this.organizerName = organizerName;
    }

    public long getRegisteredCount() {
        return registeredCount;
    }

    public void setRegisteredCount(long registeredCount) {
        this.registeredCount = registeredCount;
    }

    public long getAvailableSeats() {
        return availableSeats;
    }

    public void setAvailableSeats(long availableSeats) {
        this.availableSeats = availableSeats;
    }
}
